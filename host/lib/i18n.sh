msg() {
    local key=$1; shift
    local fmt
    if [[ "${SIEM_LANG}" == "en" ]]; then
        fmt=${MSG_EN[$key]:-${MSG_DE[$key]:-$key}}
    else
        fmt=${MSG_DE[$key]:-$key}
    fi
    # shellcheck disable=SC2059  # Format stammt aus den eigenen Texttabellen
    printf -- "$fmt" "$@"
}
